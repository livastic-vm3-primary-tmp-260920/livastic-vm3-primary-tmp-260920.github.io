"""Offline regression for the one-owner static x402 buyer acquisition guide.

No wallet, network requests, auth, KYC, chain writes, payment or browser access.
"""
from html.parser import HTMLParser
import unittest
from pathlib import Path
from xml.etree import ElementTree

BASE = Path(__file__).resolve().parents[1]
PAGE = BASE / "x402-live-api" / "index.html"
ORIGIN = "https://vm5-openapi-x402.onrender.com"
PAYEE = "0x4e3106520E40af30870caFE78da1B1e7110eD98E"
USDC = "0x833589fCD6eDb6E08f4C7C32D4f71b54bdA02913"

class LinkReader(HTMLParser):
    def __init__(self):
        super().__init__()
        self.links=[]
        self.forms=[]
        self.scripts=[]
    def handle_starttag(self, tag, attrs):
        d=dict(attrs)
        if tag == "a" and "href" in d:
            self.links.append(d["href"])
        if tag == "script":
            self.scripts.append(d)
        if tag == "form":
            self.forms.append(d)

def test_guide_is_explicitly_no_custody_and_one_owner():
    s=PAGE.read_text()
    assert "one accountable beneficial human owner" in s
    assert "No wallet connects here" in s
    assert "no browser analytics" in s
    assert "No arbitrage promise" in s
    assert PAYEE in s and USDC in s and "eip155:8453" in s
    assert "not two organic buyers" in s.lower()
    assert "not a new order generated by this page" in s.lower()

def test_exact_three_live_paid_routes_and_three_free_samples():
    parser=LinkReader();parser.feed(PAGE.read_text())
    for paid,free in (
        ("/v1/btc-funding-four-venues","/v1/btc-funding-sample"),
        ("/v1/tapeout-cpu0-report","/v1/tapeout-cpu0-sample"),
        ("/v1/tapeout-cpu0-diff","/v1/tapeout-cpu0-diff-sample"),
    ):
        assert ORIGIN+paid in parser.links
        assert ORIGIN+free in parser.links
    assert all(parser.links.count(ORIGIN+route)==1 for route in ("/v1/btc-funding-four-venues","/v1/btc-funding-sample","/v1/tapeout-cpu0-report","/v1/tapeout-cpu0-sample","/v1/tapeout-cpu0-diff","/v1/tapeout-cpu0-diff-sample"))

def test_guide_does_not_collect_secrets_or_trigger_payment():
    parser=LinkReader();parser.feed(PAGE.read_text())
    assert not parser.forms and not parser.scripts
    assert "payment is not made by visiting" in PAGE.read_text().lower()
    assert "No wallet connects" in PAGE.read_text()
    assert "private keys" in PAGE.read_text()

def test_quote_amounts_accurate_atomic_units():
    s=PAGE.read_text()
    assert "0.010000 USDC / successful request" in s
    assert "0.005000 USDC / successful request" in s
    assert "10,000 atomic Base USDC units" in s
    assert "5,000 atomic Base USDC units" in s
    assert "2026-10-24 05:39 UTC" in s

def test_root_has_discoverable_buyer_url_and_metadata():
    site=(BASE/"index.html").read_text()
    llms=(BASE/"llms.txt").read_text()
    assert site.count('href="/x402-live-api/"')==2
    assert "x402-live-api/" in llms
    assert "BTC/USDT four-venue" in llms
    assert PAYEE in llms and USDC in llms

def test_sitemap_well_formed_with_unique_buyer_page():
    source=(BASE/"sitemap.xml").read_text()
    ElementTree.parse(BASE/"sitemap.xml")
    assert source.count("https://livastic-vm3-primary-tmp-260920.github.io/x402-live-api/")==1


class LiveX402BuyerGuideTests(unittest.TestCase):
    def test_one_owner_and_no_custody(self):
        test_guide_is_explicitly_no_custody_and_one_owner()

    def test_real_route_and_free_sample_links(self):
        test_exact_three_live_paid_routes_and_three_free_samples()

    def test_no_private_inputs_or_signatures(self):
        test_guide_does_not_collect_secrets_or_trigger_payment()

    def test_exact_payment_quote_units(self):
        test_quote_amounts_accurate_atomic_units()

    def test_homepage_and_machine_discovery(self):
        test_root_has_discoverable_buyer_url_and_metadata()

    def test_canonical_sitemap(self):
        test_sitemap_well_formed_with_unique_buyer_page()
